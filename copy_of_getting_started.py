import numpy as np, matplotlib.pyplot as plt
from scipy.integrate import odeint

def F(y,t):
  dy=[0,0]
  dy[0]=y[1]
  dy[1]=-25*np.sin(y[0])
  return dy

t=np.arange(0,10,0.01)
y0 = [0.5,0]

y = odeint(F,y0,t)
plt.plot(t,y[:,0])

# Fast Fourier Transform to get the spectrum

eft = np.fft.fft(y[:,0])  #[0:49]  #could also use ebox here
plt.plot(abs(eft[0:19]))
kmax = np.where(abs(eft[0:99]) == np.max(abs(eft[0:99])))
