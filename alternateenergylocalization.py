  offset = int(kernel_size/2)
  wraparound = etrace1[0:kernel_size]
  etrace2 = np.concatenate((etrace1,wraparound))
  kernel = np.ones(kernel_size) / kernel_size
  movingAverage1 = np.convolve(etrace2, kernel, mode='valid')
  movingAverage2 = np.roll(movingAverage1,offset)
  prediction = np.argmax(movingAverage2)
  return prediction

